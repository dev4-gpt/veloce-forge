// Generate the Orchestrate benchmark cases.
//   public:  src/lib/bench/orchestrateData.ts   (seeds 1..12: 6 visible + 6 field; committed)
//   private: private/heldout.json key "orchestrate" (random seeds NEVER written down; git-ignored)
// Usage: npx tsx scripts/gen-orchestrate.ts [--private N]
import { randomInt } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { makeCase } from "../src/lib/bench/orchestrateSim";

const pub = Array.from({ length: 12 }, (_, i) => makeCase(i + 1));
const body = (cs: typeof pub) => cs.map((c) => `  { input: ${JSON.stringify(c.input)}, expected: ${JSON.stringify(c.expected)} },`).join("\n");
writeFileSync(
  "src/lib/bench/orchestrateData.ts",
  `// GENERATED by scripts/gen-orchestrate.ts from public seeds 1..12. Do not edit by hand.\n` +
    `// expected = JSON {optimum2, single2}: twice the best achievable score, and twice the best single-agent score.\n` +
    `export const ORCH_VISIBLE = [\n${body(pub.slice(0, 6))}\n];\nexport const ORCH_FIELD = [\n${body(pub.slice(6))}\n];\n`,
);
console.log("public cases written:", pub.length);

const i = process.argv.indexOf("--private");
if (i > -1) {
  const n = Number(process.argv[i + 1] ?? 15);
  const seen = new Set<string>(pub.map((c) => c.input));
  const priv: { input: string; expected: string }[] = [];
  while (priv.length < n) {
    const c = makeCase(100_000 + randomInt(0, 900_000_000)); // seed is discarded; only the case is kept
    if (!seen.has(c.input)) {
      seen.add(c.input);
      priv.push(c);
    }
  }
  const file = existsSync("private/heldout.json") ? JSON.parse(readFileSync("private/heldout.json", "utf8")) : {};
  file.orchestrate = priv;
  writeFileSync("private/heldout.json", JSON.stringify(file, null, 1));
  console.log("private sealed cases written to private/heldout.json:", priv.length);
}
